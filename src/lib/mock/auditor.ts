export function getVatSplitSummary(): VatSplitSummary {
  const salesRows = MOCK_VAT_SPLIT_ROWS.filter((r) => r.direction === "SALES");
  const purchaseRows = MOCK_VAT_SPLIT_ROWS.filter((r) => r.direction === "PURCHASE");

  const salesTotalGrossNpr = salesRows.reduce((sum, r) => sum + r.totalGrossNpr, 0);
  const salesTaxableNpr = salesRows.reduce((sum, r) => sum + r.taxableAmountNpr, 0);
  const salesExemptNpr = salesRows.reduce((sum, r) => sum + r.exemptAmountNpr, 0);
  const salesOutputVatNpr = salesRows.reduce((sum, r) => sum + r.vatAmountNpr, 0);

  const purchaseTotalGrossNpr = purchaseRows.reduce((sum, r) => sum + r.totalGrossNpr, 0);
  const purchaseTaxableNpr = purchaseRows.reduce((sum, r) => sum + r.taxableAmountNpr, 0);
  const purchaseExemptNpr = purchaseRows.reduce((sum, r) => sum + r.exemptAmountNpr, 0);
  const purchaseInputVatNpr = purchaseRows.reduce((sum, r) => sum + r.vatAmountNpr, 0);

  const netVatLiabilityNpr = salesOutputVatNpr - purchaseInputVatNpr;

  return {
    salesTotalGrossNpr,
    salesTaxableNpr,
    salesExemptNpr,
    salesOutputVatNpr,
    purchaseTotalGrossNpr,
    purchaseTaxableNpr,
    purchaseExemptNpr,
    purchaseInputVatNpr,
    netVatLiabilityNpr,
  };
}

